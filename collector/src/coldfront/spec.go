package coldfront

// Column is one column of a metrics table.
type Column struct {
	// Name is the column name.
	Name string

	// PGType is the column's type in the plain-PostgreSQL schema, as
	// format_type() reports it. StorageType maps it to the type the
	// column is created with in ColdFront.
	PGType string

	// AddedIn is the migration version that added the column with
	// ALTER TABLE ... ADD COLUMN, or zero for a column created with the
	// table. A later migration's ALTER TABLE runs unchanged against the
	// ColdFront view, so such a column must already have a type
	// ColdFront stores natively.
	AddedIn int
}

// Table is the column specification of one metrics.* table.
type Table struct {
	// Name is the relation name in the metrics schema.
	Name string

	// CreatedIn is the migration version that creates the table.
	CreatedIn int

	// Columns lists every column in attribute order, including those
	// added by later migrations.
	Columns []Column
}

